// Package shell generates the two files Hiwthi owns in ~/.config/hiwthi:
// env.sh (environment and PATH, for login shells) and interactive.sh
// (editing mode, aliases, mise, for interactive shells). Both are plain
// POSIX sh that bash and zsh source alike; where the two shells differ, the
// generated code checks which one is running.
package shell

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/waco-org/hiwthi/internal/config"
)

// File names in ~/.config/hiwthi.
const (
	EnvFile         = "env.sh"
	InteractiveFile = "interactive.sh"
)

const header = `# Generated by hiwthi from common.yml and local.yml in your Hiwthi repo.
# Don't edit: "hiwthi apply" overwrites it. Change the YAML instead.
`

var (
	envName   = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	aliasName = regexp.MustCompile(`^[A-Za-z0-9_.:+@%,-]+$`)
)

// Env returns the content of env.sh.
func Env(s *config.Shell) (string, error) {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(`#
# Sourced by login shells (.bash_profile or .profile, .zshenv). Directories
# that don't exist are left out of PATH, as are environment values naming a
# path that doesn't exist. Sourcing it again changes nothing.
`)

	if len(s.Path) > 0 || len(s.PathAppend) > 0 {
		b.WriteString(`
_hiwthi_path() {
    case ":$PATH:" in
        *":$2:"*) ;;
        *) if [ -d "$2" ]; then
               if [ "$1" = prepend ]; then PATH="$2:$PATH"; else PATH="$PATH:$2"; fi
           fi ;;
    esac
}
`)
		// Prepending in reverse leaves the list in its own order, ahead of
		// the system's.
		for _, p := range slices.Backward(s.Path) {
			expr, err := pathExpr(p)
			if err != nil {
				return "", fmt.Errorf("shell.path: %w", err)
			}
			fmt.Fprintf(&b, "_hiwthi_path prepend %s\n", expr)
		}
		for _, p := range s.PathAppend {
			expr, err := pathExpr(p)
			if err != nil {
				return "", fmt.Errorf("shell.path_append: %w", err)
			}
			fmt.Fprintf(&b, "_hiwthi_path append %s\n", expr)
		}
		b.WriteString("unset -f _hiwthi_path\nexport PATH\n")
	}

	if len(s.Environment) > 0 {
		b.WriteString("\n")
		for _, name := range sortedKeys(s.Environment) {
			if !envName.MatchString(name) {
				return "", fmt.Errorf("shell.environment: %q isn't a valid variable name", name)
			}
			value := s.Environment[name]
			if isPath(value) {
				expr, err := pathExpr(value)
				if err != nil {
					return "", fmt.Errorf("shell.environment.%s: %w", name, err)
				}
				fmt.Fprintf(&b, "if [ -e %s ]; then export %s=%s; fi\n", expr, name, expr)
			} else {
				fmt.Fprintf(&b, "export %s=%s\n", name, quote(value))
			}
		}
	}
	return b.String(), nil
}

// Interactive returns the content of interactive.sh. withMise adds mise's
// activation, when the description lists tools.
func Interactive(s *config.Shell, withMise bool) (string, error) {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(`#
# Sourced by interactive shells (.bashrc, .zshrc). Ends with your own
# ~/.config/hiwthi/local.bash or local.zsh, if present.

case $- in
    *i*) ;;
    *) return 0 ;;
esac
`)

	var bash, zsh []string
	switch s.EditingMode {
	case "vi":
		bash, zsh = append(bash, "set -o vi"), append(zsh, "bindkey -v")
	case "emacs":
		bash, zsh = append(bash, "set -o emacs"), append(zsh, "bindkey -e")
	}
	if withMise {
		const activate = `if command -v mise >/dev/null 2>&1; then eval "$(mise activate %s)"; fi`
		bash = append(bash, fmt.Sprintf(activate, "bash"))
		zsh = append(zsh, fmt.Sprintf(activate, "zsh"))
	}
	bash = append(bash, `if [ -r ~/.config/hiwthi/local.bash ]; then . ~/.config/hiwthi/local.bash; fi`)
	zsh = append(zsh, `if [ -r ~/.config/hiwthi/local.zsh ]; then . ~/.config/hiwthi/local.zsh; fi`)

	if len(s.Aliases) > 0 {
		b.WriteString("\n")
		for _, name := range sortedKeys(s.Aliases) {
			if !aliasName.MatchString(name) {
				return "", fmt.Errorf("shell.aliases: %q isn't a valid alias name", name)
			}
			fmt.Fprintf(&b, "alias %s=%s\n", name, quote(s.Aliases[name]))
		}
	}

	// The local files come last, so they can override everything above.
	b.WriteString("\nif [ -n \"${ZSH_VERSION-}\" ]; then\n")
	for _, l := range zsh {
		b.WriteString("    " + l + "\n")
	}
	b.WriteString("elif [ -n \"${BASH_VERSION-}\" ]; then\n")
	for _, l := range bash {
		b.WriteString("    " + l + "\n")
	}
	b.WriteString("fi\n")
	return b.String(), nil
}

// isPath tells whether a value names a path, which Hiwthi checks exists.
func isPath(v string) bool {
	return strings.HasPrefix(v, "/") || strings.HasPrefix(v, "~")
}

// pathExpr turns a path from the YAML into a shell word, expanding a leading
// ~ to $HOME. ~user isn't supported: a home is described for its own user.
func pathExpr(p string) (string, error) {
	switch {
	case p == "~":
		return `"$HOME"`, nil
	case strings.HasPrefix(p, "~/"):
		return `"$HOME"` + quote(p[1:]), nil
	case strings.HasPrefix(p, "~"):
		return "", fmt.Errorf("%q: only ~/ is supported, not ~user", p)
	case strings.HasPrefix(p, "/"):
		return quote(p), nil
	default:
		return "", fmt.Errorf("%q: expected an absolute path or one starting with ~/", p)
	}
}

// quote returns s single-quoted for the shell: taken literally, with no
// expansion.
func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}
