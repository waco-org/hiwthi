package home

import (
	"errors"
	"fmt"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/waco-org/hiwthi/internal/config"
	"github.com/waco-org/hiwthi/internal/startup"
)

// File names in ~/.config/hiwthi.
const (
	GitFile = "gitconfig"
	HgFile  = "hgrc"
)

// lookPath finds a tool; replaced in tests.
var lookPath = exec.LookPath

// The configuration files git and Mercurial read in the home, the
// traditional one first. Hiwthi adds its include to the first that exists,
// or creates the traditional one.
var (
	gitFiles = []string{".gitconfig", ".config/git/config"}
	hgFiles  = []string{".hgrc", ".config/hg/hgrc"}
)

const identityHeader = `# Generated by hiwthi from the identity section of common.yml and local.yml.
# Don't edit: "hiwthi apply" overwrites it. Change the YAML instead.
`

// ApplyIdentity writes the identity for git and Mercurial, those of the two
// that are installed, and includes it from their configuration files.
// Without an identity section, or one with neither name nor e-mail, it does
// nothing.
func ApplyIdentity(homeDir string, c *config.Config) ([]Change, error) {
	id := c.Identity
	if id == nil || (id.Name == "" && id.Email == "") {
		return nil, nil
	}
	for _, v := range []string{id.Name, id.Email} {
		if strings.ContainsAny(v, "\n\r") {
			return nil, errors.New("identity: a name or e-mail can't span several lines")
		}
	}

	var changes []Change
	var errs []error
	tools := []struct {
		command, target, content string
		files                    []string
		line                     startup.Line
	}{
		{"git", GitFile, gitIdentity(id), gitFiles, startup.GitInclude(GitFile)},
		{"hg", HgFile, hgIdentity(id), hgFiles, startup.HgInclude(HgFile)},
	}
	for _, t := range tools {
		if _, err := lookPath(t.command); err != nil {
			continue // not installed: skipped silently
		}
		ch, err := writeOwned(homeDir, t.target, t.content)
		changes = append(changes, ch...)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		file, err := firstExisting(homeDir, t.files)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		ch, err = hook(homeDir, file, t.line)
		changes = append(changes, ch...)
		if err != nil {
			errs = append(errs, err)
		}
	}
	return changes, errors.Join(errs...)
}

func gitIdentity(id *config.Identity) string {
	var b strings.Builder
	b.WriteString(identityHeader + "\n[user]\n")
	if id.Name != "" {
		fmt.Fprintf(&b, "\tname = %s\n", gitQuote(id.Name))
	}
	if id.Email != "" {
		fmt.Fprintf(&b, "\temail = %s\n", gitQuote(id.Email))
	}
	return b.String()
}

// gitQuote quotes a value for git's configuration: double quotes keep
// leading and trailing spaces and # or ;, which would start a comment.
func gitQuote(v string) string {
	v = strings.ReplaceAll(v, `\`, `\\`)
	v = strings.ReplaceAll(v, `"`, `\"`)
	return `"` + v + `"`
}

func hgIdentity(id *config.Identity) string {
	user := id.Name
	switch {
	case id.Name == "":
		user = id.Email
	case id.Email != "":
		user = fmt.Sprintf("%s <%s>", id.Name, id.Email)
	}
	// Mercurial takes the rest of the line as it is: nothing to quote.
	return identityHeader + "\n[ui]\nusername = " + user + "\n"
}

// firstExisting returns the first of files (relative to the home) that
// exists, or the first one if none does.
func firstExisting(homeDir string, files []string) (string, error) {
	for _, f := range files {
		ok, err := exists(filepath.Join(homeDir, f))
		if err != nil || ok {
			return f, err
		}
	}
	return files[0], nil
}
